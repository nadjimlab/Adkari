    fun getAzkarByCategory(category: AzkarCategory): List<DhikrItem> {
        return allAzkar.filter { it.category == category }
    }

    fun getDhikrById(id: String): DhikrItem? {
        return allAzkar.find { it.id == id }
    }

    fun searchAzkar(query: String): List<DhikrItem> {
        if (query.isBlank()) return emptyList()
        val cleanQuery = query.trim().replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").lowercase()
        return allAzkar.filter { item ->
            val cleanText = item.textArabic.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").lowercase()
            val cleanVirtue = item.virtue.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").lowercase()
            val cleanCat = item.category.titleArabic.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا").lowercase()
            cleanText.contains(cleanQuery) || cleanVirtue.contains(cleanQuery) || cleanCat.contains(cleanQuery)
        }
    }
